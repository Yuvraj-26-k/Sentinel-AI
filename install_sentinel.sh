#!/usr/bin/env sh
set -eu

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PYTHON=${PYTHON:-python3}
VENV="$ROOT/.venv"
BIN_DIR=${XDG_BIN_HOME:-"$HOME/.local/bin"}

if ! command -v "$PYTHON" >/dev/null 2>&1; then
    printf 'Sentinel installer: %s was not found. Install Python 3.10 or newer.\n' "$PYTHON" >&2
    exit 1
fi
if ! "$PYTHON" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 10) else 1)'; then
    printf 'Sentinel installer: Python 3.10 or newer is required.\n' >&2
    exit 1
fi

if [ ! -x "$VENV/bin/python" ]; then
    "$PYTHON" -m venv "$VENV"
fi
"$VENV/bin/python" -m pip install -e "$ROOT"

mkdir -p "$BIN_DIR"
"$VENV/bin/python" - "$BIN_DIR/sentinel" "$ROOT" <<'PY'
import shlex
import sys
from pathlib import Path

launcher = Path(sys.argv[1])
root = shlex.quote(sys.argv[2])
if launcher.is_symlink():
    raise SystemExit(
        f"Refusing to replace symlink at {launcher}; remove it or choose another XDG_BIN_HOME."
    )
if launcher.exists():
    existing = launcher.read_text(encoding="utf-8", errors="replace")
    if not existing.startswith("#!/usr/bin/env sh\n# Sentinel-AI user launcher; generated by install_sentinel.sh"):
        raise SystemExit(
            f"Refusing to overwrite existing command at {launcher}; "
            "move it aside or choose another XDG_BIN_HOME."
        )
launcher.write_text(
    "#!/usr/bin/env sh\n"
    "# Sentinel-AI user launcher; generated by install_sentinel.sh\n"
    "set -eu\n"
    f"ROOT={root}\n"
    "VENV=\"$ROOT/.venv\"\n"
    "PYTHON=${PYTHON:-python3}\n"
    "if [ ! -x \"$VENV/bin/python\" ]; then\n"
    "    \"$PYTHON\" -m venv \"$VENV\"\n"
    "    \"$VENV/bin/python\" -m pip install -e \"$ROOT\"\n"
    "fi\n"
    "exec \"$VENV/bin/python\" -m sentinel \"$@\"\n",
    encoding="utf-8",
)
launcher.chmod(0o755)
PY

case ":${PATH:-}:" in
    *":$BIN_DIR:"*) ;;
    *)
        printf 'Installed the sentinel command in %s\n' "$BIN_DIR"
        if [ -t 0 ]; then
            printf 'Add %s to ~/.profile so `sentinel` works in new shells? [Y/n] ' "$BIN_DIR"
            read -r answer
        else
            answer=n
        fi
        case "${answer:-y}" in
            y|Y|yes|YES)
                "$VENV/bin/python" - "$HOME/.profile" "$BIN_DIR" <<'PY'
import shlex
import sys
from pathlib import Path

profile = Path(sys.argv[1])
bin_dir = shlex.quote(sys.argv[2])
marker = "# Sentinel-AI user command path"
existing = profile.read_text(encoding="utf-8") if profile.exists() else ""
if marker not in existing:
    with profile.open("a", encoding="utf-8") as handle:
        handle.write(
            f"\n{marker}\n"
            f'case ":$PATH:" in *:{bin_dir}:*) ;; *) PATH={bin_dir}:$PATH ;; esac\n'
            "export PATH\n"
        )
print(f"Added the command path to {profile}. Open a new shell, then run: sentinel")
PY
                ;;
            *)
                printf 'For this shell, run:\n  export PATH="%s:$PATH"\n' "$BIN_DIR"
                ;;
        esac
        ;;
esac
printf 'Installation complete. Start Sentinel with: sentinel\n'
